function getStoredLanguage() {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "es" || stored === "en") {
      return stored;
    }
  } catch {
    // Ignore storage failures and keep the default language.
  }
  return "es";
}

export function getLanguage() {
  return state.language ?? getStoredLanguage();
}

export function setLanguage(language) {
  const next = language === "en" ? "en" : "es";
  state.language = next;
  document.documentElement.lang = next === "en" ? "en" : "es";
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Ignore storage failures.
  }
  return next;
}

export function toggleLanguage() {
  return setLanguage(getLanguage() === "es" ? "en" : "es");
}

export function t(key, params = {}) {
  const language = getLanguage();
  const table = DICTIONARY[language] ?? DICTIONARY.es;
  const fallback = DICTIONARY.es[key] ?? key;
  const value = table[key] ?? fallback;
  return value.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? ""));
}
